#!/bin/bash
# SC8886S 初始化兜底脚本 (仅当内核 sc8886s 驱动未绑定 0-006b 时被服务调用)
# 关看门狗 + 1A 充电 + 打开 ADC。
# 注意 OPTION0 必须是 0x0e/0x07 (EN_IDPM|EN_LDO|IBAT_GAIN, EN_LWPWR=0,
# 看门狗关)。老版本写 0x00/0x00 会把 EN_LDO 清零 → 零输入电流 → 不充电
# (真机教训: U-Boot 配好的 0x0e 被这里冲掉, status0 恒 0)。
i2cset -y -f 0 0x6b 0x00 0x0e
i2cset -y -f 0 0x6b 0x01 0x07
i2cset -y -f 0 0x6b 0x0D 0x18
i2cset -y -f 0 0x6b 0x02 0x00
i2cset -y -f 0 0x6b 0x03 0x04
i2cset -y -f 0 0x6b 0x04 0xD0
i2cset -y -f 0 0x6b 0x05 0x20
i2cset -y -f 0 0x6b 0x0F 0x41
i2cset -y -f 0 0x6b 0x36 0x00
i2cset -y -f 0 0x6b 0x22 0x00
i2cset -y -f 0 0x6b 0x3A 0xFF
